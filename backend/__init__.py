# v0.32 起：【后台改成密钥对登录】。登录时不再传密码，而是用私钥对服务端
#           发的一次性挑战签名；服务端只存公钥（admin_keys 表），
#           所以数据库被整个拖走也进不了后台。
#           ① 验签是**纯标准库**手写的 ECDSA P-256（backend/adminkeys.py）。
#              本机实测 cryptography / ecdsa / nacl 一个都装不上，
#              而这是中小学环境部署的硬约束，所以曲线运算、DER 编码、
#              验签全部自己实现。签名用浏览器自带的 WebCrypto 算，
#              私钥永远不离开用户的电脑。
#           ② 挑战是一次性的：验证通过就在同一条 UPDATE 里标成已用，
#              不能先查后标 —— 那样中间有缝隙，签名有机会被重放。
#              按 IP 限领（60 张/时），挑战 2 分钟过期。
#           ③ 「证明身份」分两条路：名下有密钥就必须签名，一把都没有
#              才回退到密码（否则第一次永远无法生成第一把）。
#           ④ 密码入口可以关掉（admin_password_login），关掉后登录接口直接 403。
#              不允许在「只剩最后一把密钥」时删掉它 —— 那等于把自己锁在门外。
#           ⑤ 新增 python run.py --reset-admin-key 应急命令：密钥和备份全丢了、
#              只能登上服务器时，清掉密钥并重新打开密码登录。
#           ⑥ 前端：登录页多了「用密钥文件」模式（默认），选中 .mcfrkey 即可；
#              超管后台多一个「登录密钥」页签，管生成 / 删除 / 密码入口开关。
