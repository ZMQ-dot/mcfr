#              附近可见；每 28deg 一道、每道 12deg 宽。早雾时段最明显 ——
#              丁达尔效应本来就靠雾，光本身是看不见的。
#           ④ 光源真的在走：--sun-x / --sun-y 每 20 秒挪一点，配合 26 秒的
#              transform 过渡连成连续轨迹。夜里月亮**往回走**（18:00 从最右边
#              接落日的班，一路挪到 6:00 的最左边）—— 不这么做，6:00 和 18:00
#              各会有一次光源瞬移，那是「不无缝」最刺眼的样子。
#           ⑤ 四层都**不用 mix-blend-mode**，就普通 alpha 叠加。实测：screen
#              在近白的页面上等于没做（白 + 光 = 白），multiply 在深色页面上
#              又会把光压成影。普通叠加两头都对 —— 浅底是暖色光柱，深底是发光。
#           ⑥ 影子朝向 --shade-angle 是**旋转角**（atan2(dy, dx)），不是 CSS
#              渐变角（atan2(dx, -dy)）；混了会差 90°，「太阳在左上、影子往左下倒」。
